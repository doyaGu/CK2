static void MakeAviMjpegSample(AviReaderTestData &a, bool lower=false, bool omitHuffman=false) {
    a.Start(24,lower?0x67706a6du:0x47504a4du,8,8);
    uint8_t bytes[sizeof(AviPaletteJpeg)]; unsigned used=0;
    if(omitHuffman) {
        unsigned p=0;
        while(p<sizeof(AviPaletteJpeg)) {
            if(p+4<sizeof(AviPaletteJpeg)&&AviPaletteJpeg[p]==255&&AviPaletteJpeg[p+1]==0xc4) {
                p+=2+(AviPaletteJpeg[p+2]*256+AviPaletteJpeg[p+3]); continue;
            }
            bytes[used++]=AviPaletteJpeg[p++];
        }
    } else { std::memcpy(bytes,AviPaletteJpeg,sizeof(bytes)); used=sizeof(bytes); }
    a.Frame(bytes,used); a.Finish();
}
