// Independent RIFF bytes shared with the native-DLL probe, never a production writer.
struct AviReaderTestData {
    uint8_t Data[32768] = {};
    unsigned Size = 0, Frames = 0, Entries = 0, Movi = 0, Record = 0;
    unsigned FrameCountAt = 0, StreamCountAt = 0;
    struct Entry { unsigned Offset, Size, Flags; char Id[4]; } Index[64] = {};
    uint32_t Codec = 0;
    void Word(unsigned at, uint32_t value, unsigned count = 4) {
        for (unsigned i = 0; i < count; ++i) Data[at+i] = uint8_t(value >> (i*8));
    }
    void Bytes(const void *p, unsigned n) { if (n) std::memcpy(Data+Size,p,n); Size+=n; }
    unsigned Begin(const char *id) { unsigned at=Size; Bytes(id,4); Size+=4; return at; }
    unsigned List(const char *id) { unsigned at=Begin("LIST"); Bytes(id,4); return at; }
    void End(unsigned at) { Word(at+4,Size-at-8); if(Size&1) Data[Size++]=0; }
    void Start(unsigned bpp, uint32_t codec, int width=2, int height=2, bool records=false, uint32_t handler=0) {
        Size=Frames=Entries=0; std::memset(Data,0,sizeof(Data)); Codec=codec;
        Begin("RIFF"); Bytes("AVI ",4); unsigned hdrl=List("hdrl"), avih=Begin("avih"); Size+=56;
        Word(avih+8,40000); Word(avih+20,0x10); FrameCountAt=avih+24;
        Word(avih+32,1); Word(avih+40,width); Word(avih+44,height<0?-height:height); End(avih);
        unsigned strl=List("strl"), strh=Begin("strh"); Size+=56; std::memcpy(Data+strh+8,"vids",4);
        Word(strh+12,handler); Word(strh+16,bpp<=8?0x10000:0); Word(strh+28,1); Word(strh+32,25); StreamCountAt=strh+40; End(strh);
        unsigned strf=Begin("strf"); Size+=40; Word(strf+8,40); Word(strf+12,width); Word(strf+16,uint32_t(height));
        Word(strf+20,1,2); Word(strf+22,bpp,2); Word(strf+24,codec);
        Word(strf+28,((width*bpp+31)/32)*4*(height<0?-height:height));
        if (bpp<=8) {
            Word(strf+40,1u<<bpp);
            for(unsigned i=0;i<(1u<<bpp);++i) {
                const uint8_t rgb[4]={uint8_t(i==2?255:0),0,uint8_t(i==1?255:0),0}; Bytes(rgb,4);
            }
        }
        End(strf); End(strl); End(hdrl); Movi=List("movi"); Record=records?List("rec "):0;
    }
    void Add(const char *id, const void *p, unsigned n, unsigned flags) {
        Entry &e=Index[Entries++]; e.Offset=Size; e.Size=n; e.Flags=flags; std::memcpy(e.Id,id,4);
        unsigned chunk=Begin(id); Bytes(p,n); End(chunk);
    }
    void Frame(const void *p, unsigned n) { Add(Codec?"00dc":"00db",p,n,0x10); ++Frames; }
    void Palette(unsigned first, unsigned count, const uint8_t *rgb, const char *id="00pc") {
        uint8_t p[1028]={}; p[0]=uint8_t(first); p[1]=uint8_t(count);
        for(unsigned i=0;i<count;++i) { std::memcpy(p+4+i*4,rgb+i*3,3); p[7+i*4]=0; }
        Add(id,p,4+count*4,0x100);
    }
    void Finish(bool indexed=true) {
        if(Record) End(Record); End(Movi);
        if(indexed) {
            unsigned idx=Begin("idx1");
            for(unsigned i=0;i<Entries;++i) { Bytes(Index[i].Id,4); unsigned at=Size; Size+=12;
                Word(at,Index[i].Flags); Word(at+4,Index[i].Offset-Movi-8); Word(at+8,Index[i].Size); }
            End(idx);
        }
        Word(FrameCountAt,Frames); Word(StreamCountAt,Frames); End(0);
    }
};
static void MakeAviPaletteSample(AviReaderTestData &a, unsigned bpp, uint32_t codec,
                                 bool changes=true, bool records=false, bool indexed=true) {
    a.Start(bpp,codec,2,2,records);
    const uint8_t raw8[]={1,2,0,0,2,1,0,0}, raw4[]={0x12,0,0,0,0x21,0,0,0}, raw1[]={0x80,0,0,0,0x40,0,0,0};
    const uint8_t rle8[]={2,1,0,0,2,2,0,1}, rle4[]={2,0x11,0,0,2,0x22,0,1}, eob[]={0,1};
    const uint8_t *first=codec==1?rle8:codec==2?rle4:bpp==8?raw8:bpp==4?raw4:raw1;
    a.Frame(first,8);
    const uint8_t green[]={0,255,0}, yellow[]={255,255,0}, restore[]={255,0,0,0,0,255};
    if(changes) a.Palette(1,1,green);
    a.Frame(codec?eob:first,codec?2:8);
    if(changes) a.Palette(bpp==1?0:2,1,yellow);
    a.Frame(nullptr,0);
    const uint8_t restore1[]={0,0,0,255,0,0};
    if(changes) a.Palette(bpp==1?0:1,2,bpp==1?restore1:restore);
    a.Frame(codec?eob:first,codec?2:8); a.Finish(indexed);
}
static void MakeAviVideo1Sample(AviReaderTestData &a, unsigned bpp, unsigned mode, uint32_t codec=0x4d415243u) {
    a.Start(bpp,codec,4,4);
    const uint8_t solid8[]={1,0x80}, solid16[]={0,0xfc}, skip[]={1,0x84};
    const uint8_t two8[]={0xaa,0x55,1,2}, two16[]={0xaa,0x55,0,0x7c,0x1f,0};
    const uint8_t eight8[]={0xaa,0x95,1,2,2,1,1,2,2,1};
    const uint8_t eight16[]={0xaa,0x55,0,0xfc,0x1f,0,0x1f,0,0,0x7c,0,0x7c,0x1f,0,0x1f,0,0,0x7c};
    const uint8_t *data=mode==0?(bpp==8?solid8:solid16):mode==1?(bpp==8?two8:two16):(bpp==8?eight8:eight16);
    a.Frame(data,mode==0?2:mode==1?(bpp==8?4:6):(bpp==8?10:18));
    if(bpp==8) { const uint8_t green[]={0,255,0}; a.Palette(1,1,green); }
    a.Frame(skip,2); a.Frame(nullptr,0); a.Finish();
}

